const faltantes = new Set();
export function t(clave, vars = {}, lang = E.lang) {
  const dic = T[lang] || T.es;
  let s = dic[clave] ?? T.es[clave];
  if (s === undefined) {
    if (!faltantes.has(clave)) { faltantes.add(clave); console.warn('[i18n] falta', clave); }
    return clave;
  }
  if (typeof s === 'object') s = vars.n === 1 ? s.one : s.other;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

// Aplica textos a elementos con data-t="clave" (y data-t-attr="aria-label" para atributos).
export function traducir(raiz = document) {
  raiz.querySelectorAll('[data-t]').forEach((el) => {
    const attr = el.getAttribute('data-t-attr');
    if (attr) el.setAttribute(attr, t(el.dataset.t)); else el.textContent = t(el.dataset.t);
  });
  document.documentElement.lang = E.lang;
}
